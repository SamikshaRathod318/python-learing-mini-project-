def multiply(num1, num2):
    """Returns the product of two numbers."""
    return num1 * num2

print(multiply(4, 6))  
print(multiply('a', 5)) # Output: 'aaaaa'
print(multiply(5,'b')) # Output: 'bbbbb'
print(multiply('ab', 3)) # Output: 'ababab'
print(multiply(3.5, 2)) # Output: 7.0
print(multiply(3, 2.5)) # Output: 7.5